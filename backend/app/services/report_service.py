import json
from datetime import datetime
from pathlib import Path
from typing import Dict, Any, Optional
from backend.app.config import REPORTS_DIR


class ReportService:
    """
    Automated Professional Security Report Generator.
    Produces comprehensive, publication-ready dossiers for Incidents, Vulnerability Assessments,
    and Digital Forensics Cases in Markdown, JSON, and HTML.
    """

    def __init__(self, output_dir: Optional[Path] = None):
        self.output_dir = output_dir or REPORTS_DIR
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_incident_report(
        self, incident_data: Dict[str, Any], events: list[Dict[str, Any]], analyst_username: str
    ) -> Dict[str, Any]:
        """
        Builds a comprehensive Incident Investigation Dossier.
        """
        now_str = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        inc_num = incident_data.get("incident_number", "INC-XXXX")
        title = incident_data.get("title", "Untitled Incident")
        severity = incident_data.get("severity", "MEDIUM")
        confidence = incident_data.get("confidence", 0.85)
        status = incident_data.get("status", "New")
        host_id = incident_data.get("host_id", "Unknown")
        rule_name = incident_data.get("rule_name", "Detection Rule")
        mitre_tech = incident_data.get("mitre_technique_id", "N/A")
        mitre_tactic = incident_data.get("mitre_tactic", "N/A")

        # Markdown format
        md = f"""# SENTINEL-X SECURITY INCIDENT DOSSIER
**Incident Reference:** {inc_num}  
**Classification:** DEFENSIVE INVESTIGATION REPORT  
**Date Generated:** {now_str}  
**Reporting Analyst:** {analyst_username}  

---

## 1. Executive Summary

| Attribute | Value |
| :--- | :--- |
| **Incident Title** | {title} |
| **Current Status** | `{status}` |
| **Assigned Severity** | **{severity}** |
| **Correlation Confidence**| **{int(confidence * 100)}%** (Evidence-Weighted) |
| **Target Host Identity**| `{host_id}` |
| **MITRE ATT&CK Tactic** | {mitre_tactic} |
| **MITRE ATT&CK Technique**| {mitre_tech} |

### 1.1 Overview Description
{incident_data.get('description', 'No description provided.')}

---

## 2. Correlated Telemetry & Evidence Chain

Total correlated telemetry events: **{len(events)}**

| Event ID | Timestamp | Category | Source | Process / User | Evidence SHA-256 |
| :--- | :--- | :--- | :--- | :--- | :--- |
"""
        for ev in events:
            proc_or_user = ev.get("process_name") or ev.get("account_user") or "N/A"
            ev_hash = ev.get("evidence_hash", "N/A")[:16] + "..."
            ts = ev.get("timestamp")
            ts_str = ts.strftime("%Y-%m-%d %H:%M:%S") if isinstance(ts, datetime) else str(ts)
            md += f"| `{ev.get('event_id')}` | {ts_str} | `{ev.get('event_category')}` | `{ev.get('source')}` | {proc_or_user} | `{ev_hash}` |\n"

        md += f"""
---

## 3. Human-Authorized Response Actions & Containment

"""
        actions = incident_data.get("response_actions", [])
        if actions:
            md += "| Action Type | Status | Requested By | Approved By | Outcome |\n| :--- | :--- | :--- | :--- | :--- |\n"
            for act in actions:
                md += f"| `{act.get('action_type')}` | {act.get('status')} | {act.get('requested_by')} | {act.get('approved_by') or 'Pending'} | {act.get('outcome_details') or 'N/A'} |\n"
        else:
            md += "*No containment actions triggered or recorded yet.*\n"

        md += f"""
---

## 4. Analyst Investigation Notes & Resolution

{incident_data.get('resolution_notes') or 'Investigation currently active in progress.'}

*Report generated by SENTINEL-X Unified Cybersecurity Platform.*
"""

        # Save files
        filename_base = f"{inc_num}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}"
        md_path = self.output_dir / f"{filename_base}.md"
        json_path = self.output_dir / f"{filename_base}.json"

        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md)

        json_content = json.dumps(
            {"incident": incident_data, "events": events, "analyst": analyst_username, "generated_at": now_str},
            default=str,
            indent=2,
        )
        with open(json_path, "w", encoding="utf-8") as f:
            f.write(json_content)

        return {
            "title": f"Incident Dossier: {inc_num}",
            "report_type": "INCIDENT_DOSSIER",
            "content_markdown": md,
            "content_json": json_content,
            "export_filepath": str(md_path),
        }


report_service = ReportService()
